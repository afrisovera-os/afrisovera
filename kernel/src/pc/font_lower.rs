//! Lowercase letters and the apostrophe for the PC's screen (5 Nov 2026).
//!
//! The shared 8x8 font (font.rs) has capitals only -- lowercase is folded to uppercase --
//! which is fine for a phone's boot log but hard to read as a laptop's whole console. On the
//! PC, font.rs asks here first (a cfg'd statement on its existing fold line, so the ARM
//! kernel is byte-identical). Same style as the capitals: 5 pixels wide in bits 7..3, 7 rows.

