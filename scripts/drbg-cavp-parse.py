#!/usr/bin/env python3
"""Parse a NIST CAVP HMAC_DRBG .rsp file and emit test fixtures and the boot-KAT Rust constant.

Per ADR 0007 / the architect's DRBG rules, NO vector bytes are ever transcribed by hand or taken from memory:
the cloud job downloads the official CAVP DRBG zip from csrc.nist.gov, records the URL + size + sha256, extracts
HMAC_DRBG.rsp, and runs THIS parser on it. The parser reads the bytes straight from the .rsp.

It keeps only the [SHA-256] + [PredictionResistance = False] sections and, per COUNT entry, collects the SP
800-90A HMAC-DRBG test fields:
  EntropyInput, Nonce, PersonalizationString,
  EntropyInputReseed, AdditionalInputReseed   (present only in the reseed / pr_false file),
  AdditionalInput (one per Generate call, usually two),
  ReturnedBits.

Modes:
  --json OUT.json          every matching entry, as JSON, for the Rust host test (drbgvectors_pr_false.rsp and
                           drbgvectors_no_reseed.rsp both parse with this).
  --rust-const OUT.rs      a Rust `const` for the boot-time KAT, generated from COUNT=0 of the given file.
  --selftest               parse an embedded synthetic sample and check extraction; no NIST file needed.

Run with `python -I` (stdlib only).
"""
import argparse
import json
import re
import sys

# Fields that appear once per COUNT entry. Lists (AdditionalInput) are collected in order.
_SCALAR = ("EntropyInput", "Nonce", "PersonalizationString", "EntropyInputReseed", "AdditionalInputReseed", "ReturnedBits")


def parse(text):
    """Return the list of [SHA-256][PredictionResistance=False] COUNT entries in `text`."""
    entries = []
    in_sha256 = False
    pr_false = False
    cur = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            inner = line[1:-1].strip()
            # Section headers. A bare "[SHA-256]" opens a hash section; "[PredictionResistance = False]" etc.
            if "=" not in inner:
                in_sha256 = (inner == "SHA-256")
            else:
                k, v = (s.strip() for s in inner.split("=", 1))
                if k == "PredictionResistance":
                    pr_false = (v == "False")
            continue
        if "=" not in line:
            continue
        key, val = (s.strip() for s in line.split("=", 1))
        if key == "COUNT":
            if cur is not None and cur["_keep"]:
                entries.append(cur)
            cur = {"count": int(val), "AdditionalInput": [], "_keep": in_sha256 and pr_false}
            continue
        if cur is None:
            continue
        if key == "AdditionalInput":
            cur["AdditionalInput"].append(val)
        elif key in _SCALAR:
            cur[key] = val
    if cur is not None and cur["_keep"]:
        entries.append(cur)
    for e in entries:
        del e["_keep"]
    return entries


def _hexlist_to_rust(name, hexstr):
    b = bytes.fromhex(hexstr) if hexstr else b""
    body = ", ".join("0x%02x" % x for x in b)
    return "pub const %s: [u8; %d] = [%s];" % (name, len(b), body)


def rust_const(entry, rsp_sha256):
    """A Rust module for the boot KAT from one COUNT entry (expected COUNT=0, no reseed)."""
    lines = [
        "// GENERATED by scripts/drbg-cavp-parse.py from the NIST CAVP HMAC_DRBG SHA-256 .rsp.",
        "// Do not edit by hand. Source .rsp sha256: %s" % rsp_sha256,
        "// [SHA-256] [PredictionResistance = False] COUNT = %d." % entry["count"],
        _hexlist_to_rust("KAT_ENTROPY", entry.get("EntropyInput", "")),
        _hexlist_to_rust("KAT_NONCE", entry.get("Nonce", "")),
        _hexlist_to_rust("KAT_PERSONALIZATION", entry.get("PersonalizationString", "")),
        _hexlist_to_rust("KAT_RETURNED_BITS", entry.get("ReturnedBits", "")),
    ]
    adds = entry.get("AdditionalInput", [])
    for i, a in enumerate(adds):
        lines.append(_hexlist_to_rust("KAT_ADDITIONAL_INPUT_%d" % i, a))
    return "\n".join(lines) + "\n"


_SYNTH = """# synthetic CAVP-shaped sample for the parser self-test (NOT real NIST vectors)
[SHA-1]
[PredictionResistance = False]
COUNT = 0
EntropyInput = dead
Nonce = beef
PersonalizationString =
AdditionalInput =
AdditionalInput =
ReturnedBits = f00d

[SHA-256]
[PredictionResistance = False]
[EntropyInputLen = 256]
[ReturnedBitsLen = 1024]

COUNT = 0
EntropyInput = 0011
Nonce = 2233
PersonalizationString =
AdditionalInput =
AdditionalInput =
ReturnedBits = aabbccdd

COUNT = 1
EntropyInput = 4455
Nonce = 6677
PersonalizationString = 8899
AdditionalInput = 1234
AdditionalInput = 5678
ReturnedBits = eeff

[SHA-256]
[PredictionResistance = True]
COUNT = 0
EntropyInput = ffff
Nonce = ffff
ReturnedBits = ffff
"""


def selftest():
    e = parse(_SYNTH)
    # Only the two [SHA-256][PredictionResistance=False] COUNT entries survive (SHA-1 and PR=True dropped).
    assert len(e) == 2, e
    assert e[0]["count"] == 0 and e[0]["EntropyInput"] == "0011" and e[0]["Nonce"] == "2233"
    assert e[0]["PersonalizationString"] == "" and e[0]["ReturnedBits"] == "aabbccdd"
    assert e[0]["AdditionalInput"] == ["", ""]
    assert e[1]["count"] == 1 and e[1]["AdditionalInput"] == ["1234", "5678"]
    rs = rust_const(e[0], "SELFTEST")
    assert "KAT_RETURNED_BITS: [u8; 4] = [0xaa, 0xbb, 0xcc, 0xdd];" in rs, rs
    assert "KAT_ENTROPY: [u8; 2] = [0x00, 0x11];" in rs, rs
    print("drbg-cavp-parse selftest: PASS (2 entries, rust-const ok)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rsp", nargs="?", help="path to a CAVP HMAC_DRBG .rsp")
    ap.add_argument("--json")
    ap.add_argument("--rust-const")
    ap.add_argument("--rsp-sha256", default="UNKNOWN", help="sha256 of the .rsp, recorded in the generated file")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        selftest()
        return 0
    if not a.rsp:
        ap.error("a .rsp path is required unless --selftest")
    with open(a.rsp, "r", encoding="utf-8", errors="strict") as f:
        entries = parse(f.read())
    if not entries:
        print("no [SHA-256][PredictionResistance=False] entries found", file=sys.stderr)
        return 2
    if a.json:
        with open(a.json, "w", encoding="utf-8") as f:
            json.dump(entries, f, indent=2)
        print("wrote %d entries to %s" % (len(entries), a.json))
    if a.rust_const:
        c0 = next((e for e in entries if e["count"] == 0), None)
        if c0 is None:
            print("no COUNT=0 entry for the boot KAT", file=sys.stderr)
            return 2
        with open(a.rust_const, "w", encoding="utf-8") as f:
            f.write(rust_const(c0, a.rsp_sha256))
        print("wrote boot-KAT Rust constant to %s" % a.rust_const)
    return 0


if __name__ == "__main__":
    sys.exit(main())
