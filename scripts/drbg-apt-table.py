#!/usr/bin/env python3
"""drbg-apt-table: write kernel/src/drbg_apt.rs, the SP 800-90B Adaptive Proportion Test cutoffs per claimed H.

  python3 scripts/drbg-apt-table.py           # (re)write kernel/src/drbg_apt.rs
  python3 scripts/drbg-apt-table.py --check   # exit 1 if the file in the tree differs from a fresh computation

F3 step 2a (docs/design-f3-step2a-per-source-entropy.md). A strong source claims H64 = its min-entropy per 8-bit
sample in 1/64 bit (1 ..= 512). For a 512-sample window and alpha = 2^-20 (90B section 4.4.2) the cutoff is
    C = 1 + CRITBINOM(512, 2^(-H64/64), 1 - 2^-20)
where CRITBINOM(n, p, q) is the smallest k whose binomial CDF reaches q. Computed with 80-digit decimals over the
exact binomial sum, so no row depends on float rounding. Row H64 = 256 (4 bits) must be 62, today's APT_CUTOFF.
The same file gives the RCT cutoff by formula in drbg.rs (1 + ceil(20 x 64 / H64)); that needs no table.
"""
import sys
from decimal import Decimal, getcontext
from math import comb
from pathlib import Path

getcontext().prec = 80
W = 512
ALPHA_BITS = 20
OUT = Path(__file__).resolve().parent.parent / "kernel" / "src" / "drbg_apt.rs"


def critbinom(n, p, q):
    one_p = 1 - p
    cdf = Decimal(0)
    for k in range(n + 1):
        cdf += Decimal(comb(n, k)) * p ** k * one_p ** (n - k)
        if cdf >= q:
            return k
    return n


def cutoffs():
    q = 1 - Decimal(2) ** -ALPHA_BITS
    rows = []
    for h64 in range(1, 513):
        p = Decimal(2) ** (Decimal(-h64) / 64)
        rows.append(1 + critbinom(W, p, q))
    return rows


def render(rows):
    assert rows[256 - 1] == 62, "H = 4 bits must give today's APT_CUTOFF 62, got %d" % rows[255]
    lines = [
        "// GENERATED by scripts/drbg-apt-table.py. Do not edit by hand (run the script; --check verifies).",
        "// SP 800-90B 4.4.2 Adaptive Proportion Test cutoffs, window %d, alpha = 2^-%d:" % (W, ALPHA_BITS),
        "// APT_CUTOFF_BY_H64[h64 - 1] = 1 + CRITBINOM(%d, 2^(-h64/64), 1 - 2^-%d), h64 = claimed bits per 8-bit"
        % (W, ALPHA_BITS),
        "// sample x 64 (1 ..= 512). A cutoff above %d can never be reached in one window: the APT cannot trip"
        % W,
        "// there (rows h64 < %d); the RCT still can." % (1 + max(i for i, c in enumerate(rows) if c > W) + 1
                                                          if any(c > W for c in rows) else 1),
        "pub const APT_CUTOFF_BY_H64: [u16; 512] = [",
    ]
    for i in range(0, 512, 16):
        lines.append("    " + ", ".join(str(c) for c in rows[i:i + 16]) + ",")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv):
    text = render(cutoffs())
    if len(argv) > 1 and argv[1] == "--check":
        have = OUT.read_text() if OUT.exists() else ""
        if have.replace("\r\n", "\n") != text:
            print("drbg-apt-table: FAIL, kernel/src/drbg_apt.rs differs from a fresh computation")
            return 1
        print("drbg-apt-table: OK, kernel/src/drbg_apt.rs equals a fresh computation (512 rows, H64=256 -> 62)")
        return 0
    OUT.write_text(text, newline="\n")
    print("drbg-apt-table: wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
