#!/usr/bin/env python3
"""The test language `qps` (LANGUAGES_PLAN.md stage 6; the architect's OK of 15 Nov): every English string of the
catalogue with its letters swapped for accented ones the desk's font has, wrapped in [ ] and about a third longer.
A screenshot of the desk in qps shows any plain English as text that skipped the catalogue, and `desk lang fit qps`
finds tight places before a real language does.

    python3 tools/lang/pseudo.py          # rewrites the qps block in kernel/src/afriui/lang.rs
    python3 tools/lang/pseudo.py --check  # exits 1 when the block is not what the English makes (desk-lang runs it)

Kept as they are: the gaps {0} and {0#}, the plural form names before their colon and the | between forms.
An id ending in "Short" (a short form, an abbreviation by design) gets the swap and the [ ] but no padding.
Letters only from Latin-1 and Latin Extended-A, which the desk's font draws (afriui.md section 26). No network.
"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LANG_RS = os.path.join(HERE, "..", "..", "kernel", "src", "afriui", "lang.rs")
sys.path.insert(0, HERE)
from draft import catalogue  # noqa: E402

BEGIN = "// BEGIN qps: generated by tools/lang/pseudo.py from the English; do not edit by hand"
END = "// END qps"
SWAP = dict(zip("aeiouycnszgAEIOUYCNSZG",
                "àéîöüýçñšžĝ"
                "ÀÉÎÖÜÝÇÑŠŽĜ"))
FORMS = ("zero", "one", "two", "few", "many", "other")


def pseudo_text(t, pad=True):
    """One form's text: letters swapped outside the gaps, wrapped, and padded by about a third unless `pad` is off."""
    out, i = [], 0
    while i < len(t):
        if t[i] == "{":
            j = t.find("}", i)
            if j != -1 and t[i + 1:j].rstrip("#").isdigit():
                out.append(t[i:j + 1])
                i = j + 1
                continue
        out.append(SWAP.get(t[i], t[i]))
        i += 1
    body = "".join(out)
    lead = body[: len(body) - len(body.lstrip())]
    core = body.strip()
    if not pad:
        return lead + "[" + core + "]"
    return lead + "[" + core + " " + "~" * max(1, len(core) // 3) + "]"


def pseudo(en, pad=True):
    first = en.split("|", 1)[0]
    if ":" in first and first.split(":", 1)[0] in FORMS:
        parts = []
        for part in en.split("|"):
            name, text = part.split(":", 1)
            parts.append(name + ":" + pseudo_text(text, pad))
        return "|".join(parts)
    return pseudo_text(en, pad)


def rust(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def block():
    lines = [BEGIN,
             "/// The test language qps: never listed, never saved; its safety words draw in pseudo form (the architect,",
             "/// 15 Nov). Made from the English by tools/lang/pseudo.py.",
             "static QPS: [(&str, Status); COUNT] = table(&["]
    for rid, en in catalogue(LANG_RS):
        # a short form ("...Short", the designer's Spine words) is an abbreviation by design: swapped and wrapped,
        # never padded, so the place it exists for can still be met in qps
        lines.append('    (Msg::%s, "%s", Draft),' % (rid, rust(pseudo(en, pad=not rid.endswith("Short")))))
    lines += ["]);", END]
    return "\n".join(lines)


def main():
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8")
    src = io.open(LANG_RS, encoding="utf-8").read()
    a, b = src.find(BEGIN), src.find(END)
    if a < 0 or b < 0:
        sys.exit("pseudo: the qps markers are missing from lang.rs")
    new = src[:a] + block() + src[b + len(END):]
    if "--check" in sys.argv[1:]:
        if new != src:
            print("pseudo: the qps block is NOT what the English makes; run tools/lang/pseudo.py")
            sys.exit(1)
        print("pseudo: the qps block matches the English (%d ids)" % len(catalogue(LANG_RS)))
        return
    io.open(LANG_RS, "w", encoding="utf-8", newline="\n").write(new)
    print("pseudo: wrote the qps block (%d ids)" % len(catalogue(LANG_RS)))


if __name__ == "__main__":
    main()
