CHARS = [chr(c) for c in range(32, 127)]
missing = [c for c in CHARS if c not in G]
assert not missing, missing


def bitmap(ch):
    start, rows = G[ch]
    w = len(rows[0])
    out = [0] * ROWS
    for i, r in enumerate(rows):
        v = 0
        for x, p in enumerate(r):
            if p == '#':
                v |= 0x80 >> x
        out[start + i] = v
    return w, out


def rust():
    lines = [
        "//! The Sovereign face (docs/design/afriui.md section 16): AfriSovera's own bitmap font,",
        "//! generated by tools/face/face_src.py (edit the glyphs there, not here). 95 printable ASCII",
        "//! glyphs, each at most 5 pixels wide on 12 rows: capitals and figures 9 rows (CAP), x-height",
        "//! 6 rows, descenders to row 11 (LINE_H). Within a row, bit 7 is the leftmost pixel.",
        "",
        "/// Rows from a line's top to its baseline's row + 1: capitals and figures.",
        "pub const CAP: i32 = 9;",
        "/// Rows a line of text uses, descenders included.",
        "pub const LINE_H: i32 = 12;",
        "",
        "/// (width, rows) for ' ' (32) to '~' (126).",
        "static FACE: [(u8, [u8; 12]); 95] = [",
    ]
    for ch in CHARS:
        w, rows = bitmap(ch)
        show = ch if ch not in "\\'" else "\\" + ch
        lines.append("    (%d, [%s]), // '%s'" % (w, ", ".join("0x%02X" % v for v in rows), show))
    lines += [
        "];",
        "",
        "/// The glyph for a byte: its width and rows; other bytes draw as '?'.",
        "pub fn glyph(c: u8) -> (i32, &'static [u8; 12]) {",
        "    let i = if (32..=126).contains(&c) { c - 32 } else { b'?' - 32 };",
        "    let (w, ref rows) = FACE[i as usize];",
        "    (w as i32, rows)",
        "}",
        "",
    ]
    return "\n".join(lines)


def specimen(path):
    from PIL import Image
    text = ["ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz", "0123456789 !\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~",
            "Settings  Booted 0 time(s), up 12 s", "Own your device - own your future", "afrisovera> gui  quality, glyph, jumpy"]
    W, H = 360, len(text) * 14 + 8
    im = Image.new("RGB", (W, H), (0x1E, 0x18, 0x14))
    px = im.load()
    y = 4
    for line in text:
        x = 4
        for ch in line:
            w, rows = bitmap(ch)
            for r in range(ROWS):
                for c in range(w):
                    if rows[r] & (0x80 >> c) and x + c < W:
                        px[x + c, y + r] = (0xF2, 0xEA, 0xDC)
            x += w + 1
        y += 14
    im = im.resize((W * 3, H * 3), Image.NEAREST)
    im.save(path)


